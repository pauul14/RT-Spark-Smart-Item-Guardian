"""Generate include/stm32f4xx_hal_conf.h from ST's STM32CubeF4 template.

The template (BSD-3-Clause, STMicroelectronics) is taken from the installed
framework-stm32cubef4 package. Only module enables and board constants change,
so the diff against the template stays reviewable.
Usage: python tools/build/gen_hal_conf.py <template.h> <output.h>
"""
import re
import sys

KEEP = {
    "HAL_MODULE_ENABLED", "HAL_ADC_MODULE_ENABLED", "HAL_CAN_MODULE_ENABLED",
    "HAL_DMA_MODULE_ENABLED", "HAL_FLASH_MODULE_ENABLED", "HAL_SRAM_MODULE_ENABLED",
    "HAL_GPIO_MODULE_ENABLED", "HAL_EXTI_MODULE_ENABLED", "HAL_I2C_MODULE_ENABLED",
    "HAL_IWDG_MODULE_ENABLED", "HAL_PWR_MODULE_ENABLED", "HAL_RCC_MODULE_ENABLED",
    "HAL_RTC_MODULE_ENABLED", "HAL_SD_MODULE_ENABLED", "HAL_SPI_MODULE_ENABLED",
    "HAL_TIM_MODULE_ENABLED", "HAL_UART_MODULE_ENABLED", "HAL_CORTEX_MODULE_ENABLED",
}

def main(src, dst):
    text = open(src, encoding="latin-1").read()

    def module(m):
        name = m.group(1)
        return m.group(0) if name in KEEP else "/* #define %s */" % name

    text = re.sub(r"^#define (HAL_\w+_MODULE_ENABLED)\s*$", module, text, flags=re.M)
    # RT-Spark: 8 MHz crystal X2 (schematic sheet 5), 32.768 kHz crystal X1.
    text = re.sub(r"#define HSE_VALUE\s+\S+", "#define HSE_VALUE              8000000U", text)
    text = re.sub(r"#define HSE_STARTUP_TIMEOUT\s+\S+", "#define HSE_STARTUP_TIMEOUT    200U", text)
    # HAL timebase runs on TIM6 at NVIC priority 3: above
    # configMAX_SYSCALL_INTERRUPT_PRIORITY (5), so HAL timeouts keep counting
    # inside FreeRTOS critical sections. The TIM6 ISR makes no FreeRTOS calls.
    text = re.sub(r"#define  TICK_INT_PRIORITY\s+\S+", "#define  TICK_INT_PRIORITY            3U", text)
    text = re.sub(r"#define USE_SPI_CRC\s+\S+", "#define USE_SPI_CRC                     0U", text)
    header = ("/* GENERATED by tools/build/gen_hal_conf.py from ST stm32f4xx_hal_conf_template.h\n"
              " * (STM32CubeF4 1.28.1, BSD-3-Clause, (c) STMicroelectronics). Do not edit by hand. */\n")
    open(dst, "w", encoding="latin-1", newline="\n").write(header + text)

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
