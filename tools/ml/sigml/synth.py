"""SYNTHETIC IMU trials - for offline plumbing tests ONLY.

These signals are generated from simple physical caricatures (gravity + noise,
slow rotations and gait bounce, vigorous shaking). They are NOT measurements
from the RT-Spark, are never written to data/raw/, carry "synthetic": true in
their metadata, and any model trained on them is exported with
SIG_MODEL_IS_PLACEHOLDER = 1 so firmware, LCD and reports flag it.
"""
import json
import math
import os
import random

FS = 100


def _clip(v):
    return max(-32768, min(32767, int(round(v))))


def _trial(label, seconds, rng):
    n = int(seconds * FS)
    bias = [rng.uniform(-60, 60) for _ in range(3)]          # raw LSB, ~ +/-2 dps
    tilt = rng.uniform(0, 0.4)
    rows = []
    ph = [rng.uniform(0, 2 * math.pi) for _ in range(6)]
    if label == "STATIONARY":
        amp_a, amp_g, f_a, f_g = 0.0, 0.0, 0.0, 0.0
    elif label == "NORMAL_HANDLING":
        amp_a, amp_g = rng.uniform(0.08, 0.30), rng.uniform(15, 70)
        f_a, f_g = rng.uniform(1.5, 2.2), rng.uniform(0.3, 1.2)
    else:
        amp_a, amp_g = rng.uniform(0.9, 2.4), rng.uniform(180, 600)
        f_a, f_g = rng.uniform(3.0, 6.0), rng.uniform(2.5, 5.0)
    for i in range(n):
        t = i / FS
        g = [math.sin(tilt) * 4096, 0.0, math.cos(tilt) * 4096]
        dyn = [amp_a * 4096 * math.sin(2 * math.pi * f_a * t + ph[k]) * (1.0 if k == 2 else 0.6) for k in range(3)]
        if label == "ROUGH_HANDLING" and rng.random() < 0.03:
            dyn = [d + rng.uniform(-1.5, 1.5) * 4096 for d in dyn]
        acc = [g[k] + dyn[k] + rng.gauss(0, 10) for k in range(3)]
        gyr = [bias[k] + amp_g * 32.8 * math.sin(2 * math.pi * f_g * t + ph[3 + k]) + rng.gauss(0, 6) for k in range(3)]
        rows.append((i, int(t * 1e6), *[_clip(v) for v in acc], *[_clip(v) for v in gyr], 0))
    return rows, bias


def generate(root, sessions=("SYN01", "SYN02", "SYN03", "SYN04"), trials_per_class=2, seconds=24, seed=182):
    rng = random.Random(seed)
    os.makedirs(root, exist_ok=True)
    for s in sessions:
        sdir = os.path.join(root, s)
        os.makedirs(sdir, exist_ok=True)
        for label in ("STATIONARY", "NORMAL_HANDLING", "ROUGH_HANDLING"):
            for k in range(trials_per_class):
                rows, bias = _trial(label, seconds, rng)
                name = f"{label[:5]}_{k + 1:02d}"
                with open(os.path.join(sdir, name + ".csv"), "w", newline="\n") as fh:
                    fh.write("seq,t_us,ax,ay,az,gx,gy,gz,flags\n")
                    for r in rows:
                        fh.write(",".join(str(v) for v in r) + "\n")
                meta = {"session": s, "trial": name, "label": label, "gyro_bias": bias, "fs_hz": FS,
                        "synthetic": True, "note": "SYNTHETIC - generated by tools/ml/sigml/synth.py, not board data"}
                with open(os.path.join(sdir, name + ".json"), "w") as fh:
                    json.dump(meta, fh, indent=1)
