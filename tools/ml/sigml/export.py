"""Write the firmware's generated headers in src/model/.

  model_tree.h       tree arrays + identity (version, placeholder flag)
  model_config.h     preprocessing contract (window, rate, scales, feature order)
  baseline_params.h  baseline thresholds
  golden_vectors.h   held-out windows + Python features/predictions for `golden`
Floats are written with 9 significant digits, which round-trips binary32 exactly.
"""
import datetime
import os

from . import CLASSES
from . import features as F


def _f(x):
    s = "%.9g" % x
    if "e" not in s and "." not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


HEADER = ("/* GENERATED by tools/ml/train.py - do not edit.\n"
          " * {what}\n * generated_utc: {when}\n * model: {mid}  placeholder: {ph}\n */\n")


def _hdr(what, mid, ph):
    when = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    return HEADER.format(what=what, when=when, mid=mid, ph=int(ph))


def write_all(out_dir, tree, base_params, golden, model_id, placeholder, data_hash, golden_source):
    os.makedirs(out_dir, exist_ok=True)
    n = len(tree.nodes)

    with open(os.path.join(out_dir, "model_tree.h"), "w", newline="\n") as fh:
        fh.write(_hdr("Decision tree exported for src/core/model_infer.c", model_id, placeholder))
        fh.write("#ifndef SIG_MODEL_TREE_H\n#define SIG_MODEL_TREE_H\n#include <stdint.h>\n\n")
        fh.write(f'#define SIG_MODEL_VERSION "{model_id}"\n')
        fh.write(f"#define SIG_MODEL_IS_PLACEHOLDER {int(placeholder)}\n")
        fh.write(f"#define SIG_MODEL_N_NODES {n}\n#define SIG_MODEL_MAX_DEPTH {max(tree.depth, 0)}\n")
        fh.write(f'#define SIG_MODEL_DATA_HASH "{data_hash}"\n\n')
        fh.write("/* feature index per node, -1 = leaf */\n")
        fh.write("static const int8_t sig_tree_feature[SIG_MODEL_N_NODES] = {"
                 + ", ".join(str(nd.feature) for nd in tree.nodes) + "};\n")
        fh.write("static const float sig_tree_threshold[SIG_MODEL_N_NODES] = {"
                 + ", ".join(_f(nd.threshold) for nd in tree.nodes) + "};\n")
        fh.write("static const int16_t sig_tree_left[SIG_MODEL_N_NODES] = {"
                 + ", ".join(str(nd.left) for nd in tree.nodes) + "};\n")
        fh.write("static const int16_t sig_tree_right[SIG_MODEL_N_NODES] = {"
                 + ", ".join(str(nd.right) for nd in tree.nodes) + "};\n")
        fh.write("static const uint8_t sig_tree_class[SIG_MODEL_N_NODES] = {"
                 + ", ".join(str(nd.cls) for nd in tree.nodes) + "};\n")
        fh.write("static const uint8_t sig_tree_purity_pct[SIG_MODEL_N_NODES] = {"
                 + ", ".join(str(nd.purity_pct) for nd in tree.nodes) + "};\n\n")
        fh.write("#endif\n")

    with open(os.path.join(out_dir, "model_config.h"), "w", newline="\n") as fh:
        fh.write(_hdr("Preprocessing contract the model was trained with", model_id, placeholder))
        fh.write("#ifndef SIG_MODEL_CONFIG_H\n#define SIG_MODEL_CONFIG_H\n\n")
        fh.write(f"#define SIG_MODEL_FS_HZ {F.FS_HZ}\n#define SIG_MODEL_WINDOW_SAMPLES {F.WINDOW_SAMPLES}\n")
        fh.write(f"#define SIG_MODEL_HOP_SAMPLES {F.HOP_SAMPLES}\n#define SIG_MODEL_N_FEATURES {F.N_FEATURES}\n")
        fh.write(f"#define SIG_MODEL_ACC_LSB_PER_G {F.ACC_LSB_PER_G}f\n#define SIG_MODEL_GYRO_LSB_PER_DPS {F.GYRO_LSB_PER_DPS}f\n")
        fh.write("/* feature order: " + ", ".join(F.FEATURE_NAMES) + " */\n")
        fh.write("/* classes: " + ", ".join(f"{i}={c}" for i, c in enumerate(CLASSES)) + " */\n\n#endif\n")

    with open(os.path.join(out_dir, "baseline_params.h"), "w", newline="\n") as fh:
        fh.write(_hdr("Rule baseline thresholds (tuned on training sessions only)", model_id, placeholder))
        fh.write("#ifndef SIG_BASELINE_PARAMS_H\n#define SIG_BASELINE_PARAMS_H\n")
        fh.write(f"#define SIG_BASE_STILL_ACC_STD  {_f(base_params['still_acc_std'])}\n")
        fh.write(f"#define SIG_BASE_STILL_GYRO_MAX {_f(base_params['still_gyro_max'])}\n")
        fh.write(f"#define SIG_BASE_ROUGH_DEV_MAX  {_f(base_params['rough_dev_max'])}\n")
        fh.write(f"#define SIG_BASE_ROUGH_GYRO_MAX {_f(base_params['rough_gyro_max'])}\n#endif\n")

    with open(os.path.join(out_dir, "golden_vectors.h"), "w", newline="\n") as fh:
        fh.write(_hdr("Held-out windows for the on-target `golden` self-test", model_id, placeholder))
        fh.write("#ifndef SIG_GOLDEN_VECTORS_H\n#define SIG_GOLDEN_VECTORS_H\n#include \"sig_types.h\"\n"
                 "#include \"features.h\"\n\n")
        fh.write(f'#define SIG_GOLDEN_SOURCE "{golden_source}"\n#define SIG_GOLDEN_COUNT {len(golden)}\n\n')
        fh.write("typedef struct {\n    const char *id;\n    uint8_t label;\n    uint8_t python_pred;\n"
                 "    float bias[3];\n    float features[SIG_N_FEATURES];\n    const sig_raw_imu_t *samples;\n} sig_golden_t;\n\n")
        for k, (w, pred) in enumerate(golden):
            fh.write(f"static const sig_raw_imu_t sig_golden_s{k}[SIG_WINDOW_SAMPLES] = {{\n")
            for i in range(0, len(w.raw), 4):
                fh.write("    " + " ".join("{%d,%d,%d,%d,%d,%d}," % tuple(r) for r in w.raw[i:i + 4]) + "\n")
            fh.write("};\n")
        fh.write("\nstatic const sig_golden_t sig_golden[SIG_GOLDEN_COUNT > 0 ? SIG_GOLDEN_COUNT : 1] = {\n")
        for k, (w, pred) in enumerate(golden):
            b = ", ".join(_f(F.f32(v)) for v in w.gyro_bias)
            feats = ", ".join(_f(v) for v in w.features)
            fh.write(f'    {{"{w.wid}", {w.label}, {pred}, {{{b}}},\n     {{{feats}}},\n     sig_golden_s{k}}},\n')
        fh.write("};\n\n#endif\n")
